from __future__ import annotations

from pathlib import Path
from typing import Any

from .fingerprints import sha256_json
from .io import read_json, write_json_atomic, write_text_atomic
from .state import load_or_create, save


def assemble(workflow_dir: Path, config: dict[str, Any], plan: dict[str, Any]) -> Path:
    state = load_or_create(workflow_dir, str(config["workflow_id"]))
    if any(item["status"] != "validated" for item in state["batches"]):
        raise ValueError("all batches must be validated before assembly")
    sections = [f"# {config['workflow_id']} Results", "", "Generated by Context Loom.", ""]
    trace: list[dict[str, Any]] = []
    for task in plan["tasks"]:
        result = read_json(workflow_dir / ".context-loom" / "results" / f"{task['task_id']}.json")
        sections += [f"## {task['task_id']}: {task['title']}", "", str(result.get("content", "")).rstrip(), ""]
        trace.append({"task_id": task["task_id"], "batch_id": state["tasks"][task["task_id"]]["batch_id"], "result_file": f"results/{task['task_id']}.json"})
    output = workflow_dir / ".context-loom" / "assembled.md"
    write_text_atomic(output, "\n".join(sections))
    trace_data = {"schema_version": "context-loom/trace-v1", "workflow_id": config["workflow_id"], "tasks": trace}
    write_json_atomic(workflow_dir / ".context-loom" / "trace.json", trace_data)
    state["assembly"] = {"status": "validated", "output": "assembled.md", "sha256": sha256_json(trace_data)}
    save(workflow_dir, state)
    return output

